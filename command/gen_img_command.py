async def brat_cmd(client, message):
    em = Emoji(client)
    await em.get()
    prompt = client.get_text(message)
    proses = await animate_proses(message, em.proses)

    if not prompt:
        return await proses.edit(
            f"{em.gagal}<b>Please give a prompt!</b>"
            f"Example: <code>{message.text.split()[0]} aku ganteng</code>"
        )

    file_path = None
    try:
        api_url = (
            "https://api.botcahx.eu.org/api/maker/brat"
            f"?text={quote_plus(prompt)}&apikey={API_BOTCHAX}"
        )
        response = await Tools.fetch.get(api_url)
        content_type = response.headers.get("Content-Type", "")

        if response.status_code != 200 or not content_type.startswith("image/"):
            return await proses.edit(f"{em.gagal}<b>Please try again later!</b>")

        file_path = f"brat_{uuid.uuid4().hex}.webp"
        async with aiofiles.open(file_path, "wb") as file:
            await file.write(response.content)

        await client.send_sticker(chat_id=message.chat.id, sticker=file_path)
        return await proses.delete()

    except Exception as error:
        return await proses.edit(f"{em.gagal}<b>ERROR:</b><code>{str(error)}</code>")
    finally:
        if file_path and os.path.exists(file_path):
            os.remove(file_path)


