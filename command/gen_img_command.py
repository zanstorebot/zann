def find_image_url(data):
    if isinstance(data, str):
        return data if data.startswith("http") else None
    if isinstance(data, dict):
        for value in data.values():
            result = find_image_url(value)
            if result:
                return result
    if isinstance(data, list):
        for value in data:
            result = find_image_url(value)
            if result:
                return result
    return None

