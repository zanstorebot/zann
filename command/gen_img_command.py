async def gen_bing_ai(folder_name, prompt):
    prompt_clean = re.sub(r"[^ -~]", "", prompt.strip())
    cookies_file = "storage/cookies/bing/bing.json"
    cookie_manager = BingCookies(cookies_file)
    os.makedirs(folder_name, exist_ok=True)

    while True:
        cookie = cookie_manager.get_next_cookie()
        if cookie is None:
            cookie_manager.reset()
            return None, None

        image_generator = AsyncImageGenerator(
            auth_cookie_u=cookie["auth_cookie_u"],
            auth_cookie_srchhpgusr=cookie["auth_cookie_srchhpgusr"],
        )

        try:
            images = await image_generator.generate(prompt=prompt_clean, num_images=4, max_cycles=4)
            logger.info(f"Bing images: {images}")
            await image_generator.save(images=images, output_dir=folder_name)

            files = [
                os.path.join(folder_name, name)
                for name in os.listdir(folder_name)
                if name.lower().endswith((".jpeg", ".jpg", ".png"))
            ]

            if files:
                cookie_manager.reset()
                return folder_name, files

        except Exception as error:
            logger.error(f"Bing generate error: {error}")
            continue


async def bingai_cmd(client, message):
    emo = Emoji(client)
    await emo.get()
    prompt = client.get_text(message)

    if not prompt:
        return await message.reply(
            f"{emo.gagal}<b>Give the prompt you want to generate!</b>"
            f"Example: <code>{message.text.split()[0]} beautiful anime girl</code>"
        )

    pros = await message.reply(f"{emo.proses}<b>Generating image for:</b><code>{prompt}</code>")
    folder_name = f"downloads/{client.me.id}/bingai_{uuid.uuid4().hex}"

    try:
        folder_name, images = await gen_bing_ai(folder_name, prompt)

        if not images:
            shutil.rmtree(folder_name, ignore_errors=True)
            return await pros.edit(f"{emo.gagal}<b>Images not found or failed to generate.</b>")

        media_group = []
        for image_path in images:
            if os.path.exists(image_path):
                media_group.append(
                    InputMediaPhoto(
                        media=image_path,
                        caption=f"{emo.sukses}<b>Successfully generated image.</b>",
                    )
                )

        if not media_group:
            shutil.rmtree(folder_name, ignore_errors=True)
            return await pros.edit(f"{emo.gagal}<b>No valid images were generated.</b>")

        await client.send_media_group(
            chat_id=message.chat.id,
            media=media_group,
            reply_to_message_id=message.id,
        )
        await pros.delete()
        shutil.rmtree(folder_name, ignore_errors=True)

    except Exception as error:
        logger.error(f"Bing AI error:{traceback.format_exc()}")
        error_message = str(error)

        if "Failed to decode" in error_message:
            return await pros.edit(f"{emo.gagal}<b>Failed to generate image. Please try again.</b>")

        return await pros.edit(f"{emo.gagal}<b>Error:</b><code>{error_message[:500]}</code>")


